// Ferret: differential KUnit test for the Rust CRC-CCITT implementation.
//
// Compares the Rust implementation (crc_ccitt() and the exported
// crc_ccitt_table[] from lib/crc/crc_ccitt_rust.rs) with the original C
// implementation compiled under test-only symbols
// (lib/crc/crc_ccitt_ref.o, built from the unmodified lib/crc/crc-ccitt.c with
// -Dcrc_ccitt=crc_ccitt_c_ref -Dcrc_ccitt_table=crc_ccitt_table_c_ref).
//
// The table is part of the ABI: include/linux/crc-ccitt.h keeps
// crc_ccitt_byte() as an inline that indexes the exported table, so the test
// checks every entry as well as the function results.
//
// This suite is only built for CONFIG_CRC_CCITT_DIFF_KUNIT_TEST=y and is never
// part of a production kernel.

#include <kunit/test.h>
#include <linux/crc-ccitt.h>
#include <linux/prandom.h>
#include <linux/types.h>

extern u16 crc_ccitt_c_ref(u16 crc, const u8 *buffer, size_t len);
extern u16 const crc_ccitt_table_c_ref[256];

static void crc_ccitt_diff_table(struct kunit *test)
{
	/*
	 * The Rust table is generated by a const fn, the C table is a literal.
	 * A single wrong entry would silently corrupt every caller of the inline
	 * crc_ccitt_byte(), so compare all 256 entries.
	 */
	for (int i = 0; i < 256; i++)
		KUNIT_ASSERT_EQ_MSG(test, crc_ccitt_table[i],
				    crc_ccitt_table_c_ref[i], "table[%d]", i);

	/* A few well-known upstream entries, as a self-check of the test. */
	KUNIT_EXPECT_EQ(test, crc_ccitt_table[0], 0x0000);
	KUNIT_EXPECT_EQ(test, crc_ccitt_table[1], 0x1189);
	KUNIT_EXPECT_EQ(test, crc_ccitt_table[128], 0x8408);
}

static void crc_ccitt_diff_edge_cases(struct kunit *test)
{
	/* Length 0 must not dereference the pointer. */
	KUNIT_EXPECT_EQ(test, crc_ccitt(0, NULL, 0),
			crc_ccitt_c_ref(0, NULL, 0));
	KUNIT_EXPECT_EQ(test, crc_ccitt(0xffff, NULL, 0),
			crc_ccitt_c_ref(0xffff, NULL, 0));

	/*
	 * All 65536 initial values over a single byte. This also proves that
	 * the inline crc_ccitt_byte() (which reads the Rust table) agrees with
	 * the original C implementation for every possible table index.
	 */
	for (u32 crc = 0; crc <= 0xffff; crc++) {
		u8 b = 0xa5;

		KUNIT_ASSERT_EQ_MSG(test, crc_ccitt_byte((u16)crc, b),
				    crc_ccitt_c_ref((u16)crc, &b, 1),
				    "crc=0x%04x", crc);
	}

	/* Boundary lengths and unaligned starts. */
	{
		u8 buf[1024];

		for (size_t i = 0; i < sizeof(buf); i++)
			buf[i] = (u8)(i * 37 + 11);

		for (size_t len = 0; len <= 64; len++) {
			for (size_t off = 0; off < 16; off++) {
				u16 init = (u16)(len * 131 + off);

				KUNIT_ASSERT_EQ_MSG(test,
					crc_ccitt(init, buf + off, len),
					crc_ccitt_c_ref(init, buf + off, len),
					"len=%zu off=%zu", len, off);
			}
		}
	}
}

static void crc_ccitt_diff_random_streams(struct kunit *test)
{
	struct rnd_state rng;
	u8 buf[1024];

	prandom_seed_state(&rng, 0x6363697474); /* "ccitt" */

	for (int iter = 0; iter < 2000; iter++) {
		u16 init = (u16)prandom_u32_state(&rng);
		size_t len = prandom_u32_state(&rng) % (sizeof(buf) + 1);
		size_t off = prandom_u32_state(&rng) % (sizeof(buf) - len + 1);

		prandom_bytes_state(&rng, buf, sizeof(buf));

		KUNIT_ASSERT_EQ_MSG(test, crc_ccitt(init, buf + off, len),
				    crc_ccitt_c_ref(init, buf + off, len),
				    "iter=%d len=%zu off=%zu init=0x%04x",
				    iter, len, off, init);
	}
}

static struct kunit_case crc_ccitt_diff_cases[] = {
	KUNIT_CASE(crc_ccitt_diff_table),
	KUNIT_CASE(crc_ccitt_diff_edge_cases),
	KUNIT_CASE(crc_ccitt_diff_random_streams),
	{}
};

static struct kunit_suite crc_ccitt_diff_suite = {
	.name = "crc_ccitt_diff",
	.test_cases = crc_ccitt_diff_cases,
};
kunit_test_suite(crc_ccitt_diff_suite);

MODULE_DESCRIPTION("Ferret differential test: Rust CRC-CCITT vs original C");

/// Copy elements from userspace into the FIFO.
///
/// Returns the number of elements that could not be copied and stores the
/// number of copied bytes in `copied`. This mirrors the C helper
/// `kfifo_copy_from_user()`.
fn copy_from_user(
    fifo: &mut Kfifo,
    from: *const c_void,
    len: usize,
    off: u32,
    copied: *mut c_uint,
) -> u32 {
    let esize = fifo.esize as usize;
    let size = buffer_len(fifo);
    let off = ((off & fifo.mask) as usize) * esize;
    let len = len * esize;

    let l = core::cmp::min(len, size - off);

    // SAFETY: `buf` is the FIFO buffer, valid for `size` bytes, and `off` is
    // within it. `from` is a userspace pointer supplied by the caller;
    // `copy_from_user()` validates it and reports the number of bytes it
    // could not copy.
    let not_copied = unsafe {
        let buf = buffer_mut(fifo);
        let mut ret = bindings::copy_from_user(buf.as_mut_ptr().add(off).cast(), from, l)
            as usize;

        if ret == 0 && l < len {
            ret = bindings::copy_from_user(
                buf.as_mut_ptr().cast(),
                from.cast::<u8>().add(l).cast(),
                len - l,
            ) as usize;
        } else if ret != 0 {
            // The second copy is not attempted when the first one fails, so
            // the bytes that were never tried count as not copied.
            ret += len - l;
        }

        ret
    };

    // The C original issues `smp_wmb()` here.
    fence(Ordering::Release);

    let elems = div_round_up(not_copied, esize) as u32;
    let copied_bytes = len.wrapping_sub(elems as usize * esize);

    // SAFETY: the caller guarantees `copied` is writable.
    unsafe { *copied = copied_bytes as u32 };

    elems
}

/// Copy elements from the FIFO to userspace.
///
/// Returns the number of elements that could not be copied and stores the
/// number of copied bytes in `copied`. This mirrors the C helper
/// `kfifo_copy_to_user()`.
fn copy_to_user(
    fifo: &mut Kfifo,
    to: *mut c_void,
    len: usize,
    off: u32,
    copied: *mut c_uint,
) -> u32 {
    let esize = fifo.esize as usize;
    let size = buffer_len(fifo);
    let off = ((off & fifo.mask) as usize) * esize;
    let len = len * esize;

    let l = core::cmp::min(len, size - off);

    // SAFETY: `buf` is the FIFO buffer, valid for `size` bytes, and `off` is
    // within it. `to` is a userspace pointer supplied by the caller;
    // `copy_to_user()` validates it and reports the number of bytes it could
    // not copy.
    let not_copied = unsafe {
        let buf = buffer(fifo);
        let mut ret = bindings::copy_to_user(
            to.cast::<u8>().cast(),
            buf.as_ptr().add(off).cast(),
            l,
        ) as usize;

        if ret == 0 && l < len {
            ret = bindings::copy_to_user(
                to.cast::<u8>().add(l).cast(),
                buf.as_ptr().cast(),
                len - l,
            ) as usize;
        } else if ret != 0 {
            ret += len - l;
        }

        ret
    };

    // The C original issues `smp_wmb()` here.
    fence(Ordering::Release);

    let elems = div_round_up(not_copied, esize) as u32;
    let copied_bytes = len.wrapping_sub(elems as usize * esize);

    // SAFETY: the caller guarantees `copied` is writable.
    unsafe { *copied = copied_bytes as u32 };

    elems
}


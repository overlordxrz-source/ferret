/// Set the DMA length of a scatterlist entry.
///
/// `sg_dma_len()` is a macro that writes to `dma_length` when
/// `CONFIG_NEED_SG_DMA_LENGTH` is set and to `length` otherwise, so the Rust
/// code has to pick the same field the C macro would.
#[cfg(CONFIG_NEED_SG_DMA_LENGTH)]
fn set_sg_dma_len(sgl: *mut bindings::scatterlist, len: c_uint) {
    // SAFETY: the caller guarantees `sgl` is a valid scatterlist entry.
    unsafe { (*sgl).dma_length = len };
}

/// Set the DMA length of a scatterlist entry.
///
/// See the `CONFIG_NEED_SG_DMA_LENGTH` variant above.
#[cfg(not(CONFIG_NEED_SG_DMA_LENGTH))]
fn set_sg_dma_len(sgl: *mut bindings::scatterlist, len: c_uint) {
    // SAFETY: the caller guarantees `sgl` is a valid scatterlist entry.
    unsafe { (*sgl).length = len };
}

/// Fill one scatterlist entry with a part of the FIFO buffer.
///
/// Mirrors the C helper `setup_sgl_buf()`.
fn setup_sgl_buf(
    fifo: &Kfifo,
    sgl: *mut bindings::scatterlist,
    data_offset: usize,
    nents: c_int,
    len: usize,
    dma: bindings::dma_addr_t,
) -> u32 {
    if nents == 0 || len == 0 {
        return 0;
    }

    let buf = fifo.data.cast::<u8>().wrapping_add(data_offset);

    // SAFETY: `sgl` is a valid scatterlist entry (the caller checked
    // `nents`), `buf` points inside the FIFO buffer and `len` is the number
    // of bytes that are valid there.
    unsafe {
        bindings::sg_set_buf(sgl, buf.cast(), len as c_uint);

        if dma != DMA_MAPPING_ERROR {
            (*sgl).dma_address = dma.wrapping_add(data_offset as u64);
            set_sg_dma_len(sgl, len as c_uint);
        }
    }

    1
}

/// Fill a scatterlist with the FIFO buffer, splitting it at the wrap point.
///
/// Mirrors the C helper `setup_sgl()`.
fn setup_sgl(
    fifo: &Kfifo,
    sgl: *mut bindings::scatterlist,
    nents: c_int,
    len: c_uint,
    off: u32,
    dma: bindings::dma_addr_t,
) -> u32 {
    let esize = fifo.esize as usize;
    let size = (fifo.mask as usize + 1) * esize;
    let off = ((off & fifo.mask) as usize) * esize;
    let len = len as usize * esize;

    let len_to_end = core::cmp::min(len, size - off);

    let mut n = setup_sgl_buf(fifo, sgl, off, nents, len_to_end, dma);

    // SAFETY: `n` entries have been filled, so `sgl + n` is still within the
    // caller's array as long as `nents - n` is positive, which
    // `setup_sgl_buf()` checks.
    n += setup_sgl_buf(
        fifo,
        // SAFETY: see above.
        unsafe { sgl.add(n as usize) },
        0,
        nents - n as c_int,
        len - len_to_end,
        dma,
    );

    n
}


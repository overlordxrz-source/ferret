/// Copy a record from userspace into the FIFO.
///
/// C: `int __kfifo_from_user_r(struct __kfifo *fifo, const void __user *from, unsigned long len, unsigned int *copied, size_t recsize)`
///
/// # Safety
///
/// `fifo` must point to a valid `struct __kfifo`, `from` must be a valid
/// userspace pointer and `copied` must be writable.
#[export]
pub unsafe extern "C" fn __kfifo_from_user_r(
    fifo: *mut Kfifo,
    from: *const c_void,
    len: usize,
    copied: *mut c_uint,
    recsize: usize,
) -> c_int {
    // SAFETY: the caller passes a valid `struct __kfifo`.
    let fifo = unsafe { &mut *fifo };

    let recsize = recsize;
    // SAFETY: the function has no pointer arguments.
    let len = unsafe { __kfifo_max_r(len as c_uint, recsize) } as usize;

    if len + recsize > unused(fifo) as usize {
        // SAFETY: the caller guarantees `copied` is writable.
        unsafe { *copied = 0 };
        return 0;
    }

    poke_n(fifo, len as u32, recsize);

    let in_ = fifo.in_;
    let not_copied = copy_from_user(
        fifo,
        from,
        len,
        in_.wrapping_add(recsize as u32),
        copied,
    );

    if not_copied != 0 {
        // SAFETY: the caller guarantees `copied` is writable.
        unsafe { *copied = 0 };
        return EFAULT.to_errno();
    }

    fifo.in_ = in_.wrapping_add((len + recsize) as u32);

    0
}

/// Copy a record from the FIFO to userspace and remove it.
///
/// C: `int __kfifo_to_user_r(struct __kfifo *fifo, void __user *to, unsigned long len, unsigned int *copied, size_t recsize)`
///
/// # Safety
///
/// `fifo` must point to a valid `struct __kfifo`, `to` must be a valid
/// userspace pointer and `copied` must be writable.
#[export]
pub unsafe extern "C" fn __kfifo_to_user_r(
    fifo: *mut Kfifo,
    to: *mut c_void,
    len: usize,
    copied: *mut c_uint,
    recsize: usize,
) -> c_int {
    // SAFETY: the caller passes a valid `struct __kfifo`.
    let fifo = unsafe { &mut *fifo };

    if fifo.in_ == fifo.out {
        // SAFETY: the caller guarantees `copied` is writable.
        unsafe { *copied = 0 };
        return 0;
    }

    let recsize = recsize;
    let n = peek_n(fifo, recsize);
    let mut len = len;

    if len > n as usize {
        len = n as usize;
    }

    let out = fifo.out;
    let not_copied = copy_to_user(fifo, to, len as usize, out.wrapping_add(recsize as u32), copied);

    if not_copied != 0 {
        // SAFETY: the caller guarantees `copied` is writable.
        unsafe { *copied = 0 };
        return EFAULT.to_errno();
    }

    fifo.out = out.wrapping_add(n.wrapping_add(recsize as u32));

    0
}

/// Prepare a scatterlist for a DMA transfer of a record into the FIFO.
///
/// C: `unsigned int __kfifo_dma_in_prepare_r(struct __kfifo *fifo, struct scatterlist *sgl, int nents, unsigned int len, size_t recsize, dma_addr_t dma)`
///
/// # Safety
///
/// `fifo` must point to a valid `struct __kfifo` and `sgl` must point to
/// `nents` valid scatterlist entries.
#[export]
pub unsafe extern "C" fn __kfifo_dma_in_prepare_r(
    fifo: *mut Kfifo,
    sgl: *mut bindings::scatterlist,
    nents: c_int,
    len: c_uint,
    recsize: usize,
    dma: bindings::dma_addr_t,
) -> c_uint {
    // SAFETY: the caller passes a valid `struct __kfifo`.
    let fifo = unsafe { &mut *fifo };

    // The C original uses BUG_ON(!nents): a caller contract violation, which
    // aborts the kernel there and aborts it here as well.
    assert!(nents > 0, "kfifo: nents must be greater than zero");

    let recsize = recsize;
    // SAFETY: the function has no pointer arguments.
    let len = unsafe { __kfifo_max_r(len, recsize) };

    if len as usize + recsize > unused(fifo) as usize {
        return 0;
    }

    let in_ = fifo.in_;

    setup_sgl(
        fifo,
        sgl,
        nents,
        len,
        in_.wrapping_add(recsize as u32),
        dma,
    )
}


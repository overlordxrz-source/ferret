            let fifo = unsafe { core::mem::zeroed::<Kfifo>() };
            let mut test = TestFifo {
                fifo,
                buffer: [0u8; 64],
            };

            // SAFETY: `buffer` is valid for 64 bytes and `fifo` is a valid
            // `struct __kfifo`.

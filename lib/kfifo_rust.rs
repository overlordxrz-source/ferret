/// The largest length that fits in a record of `recsize` bytes.
///
/// C: `unsigned int __kfifo_max_r(unsigned int len, size_t recsize)`
#[export]
pub unsafe extern "C" fn __kfifo_max_r(len: c_uint, recsize: usize) -> c_uint {
    // The C code computes `(1 << (recsize << 3)) - 1` in a 32-bit int, which
    // is undefined for a record size of four bytes or more.
    let bits = recsize.saturating_mul(8);
    let max = if bits >= 32 {
        u32::MAX
    } else {
        (1u32 << bits) - 1
    };

    if len > max {
        max
    } else {
        len
    }
}

/// The length of the record at the head of the FIFO.
///
/// C: `unsigned int __kfifo_len_r(struct __kfifo *fifo, size_t recsize)`
///
/// # Safety
///
/// `fifo` must point to a valid `struct __kfifo`.
#[export]
pub unsafe extern "C" fn __kfifo_len_r(fifo: *mut Kfifo, recsize: usize) -> c_uint {
    // SAFETY: the caller passes a valid `struct __kfifo`.
    let fifo = unsafe { &mut *fifo };

    peek_n(fifo, recsize)
}

/// Copy a record into the FIFO.
///
/// C: `unsigned int __kfifo_in_r(struct __kfifo *fifo, const void *buf, unsigned int len, size_t recsize)`
///
/// # Safety
///
/// `fifo` must point to a valid `struct __kfifo`, and `buf` must be valid for
/// `len` bytes.
#[export]
pub unsafe extern "C" fn __kfifo_in_r(
    fifo: *mut Kfifo,
    buf: *const c_void,
    len: c_uint,
    recsize: usize,
) -> c_uint {
    // SAFETY: the caller passes a valid `struct __kfifo`.
    let fifo = unsafe { &mut *fifo };

    let recsize = recsize;

    if len as usize + recsize > unused(fifo) as usize {
        return 0;
    }

    poke_n(fifo, len, recsize);

    let esize = fifo.esize as usize;
    let in_ = fifo.in_;

    // SAFETY: `buf` is valid for the record (the C contract).
    let src = unsafe { core::slice::from_raw_parts(buf.cast::<u8>(), len as usize * esize) };

    copy_in(fifo, src, len, in_.wrapping_add(recsize as u32));
    fifo.in_ = in_.wrapping_add(len.wrapping_add(recsize as u32));

    len
}

/// Copy a record out of the FIFO without removing it.
///
/// C: `unsigned int __kfifo_out_peek_r(struct __kfifo *fifo, void *buf, unsigned int len, size_t recsize)`
///
/// # Safety
///
/// `fifo` must point to a valid `struct __kfifo`, and `buf` must be valid for
/// `len` bytes.
#[export]
pub unsafe extern "C" fn __kfifo_out_peek_r(
    fifo: *mut Kfifo,
    buf: *mut c_void,
    len: c_uint,
    recsize: usize,
) -> c_uint {
    // SAFETY: the caller passes a valid `struct __kfifo`.
    let fifo = unsafe { &mut *fifo };

    if fifo.in_ == fifo.out {
        return 0;
    }

    let n = peek_n(fifo, recsize);
    let mut len = len;

    if len > n {
        len = n;
    }

    let esize = fifo.esize as usize;
    let out = fifo.out;

    // SAFETY: `buf` is valid for the record (the C contract).
    let dst = unsafe { core::slice::from_raw_parts_mut(buf.cast::<u8>(), len as usize * esize) };

    copy_out(fifo, dst, len, out.wrapping_add(recsize as u32));

    len
}

/// Return the offset of the first record that can be read linearly.
///
/// C: `unsigned int __kfifo_out_linear_r(struct __kfifo *fifo, unsigned int *tail, unsigned int n, size_t recsize)`
///
/// # Safety
///
/// `fifo` must point to a valid `struct __kfifo`, and `tail` must be null or
/// point to a valid `unsigned int`.
#[export]
pub unsafe extern "C" fn __kfifo_out_linear_r(
    fifo: *mut Kfifo,
    tail: *mut c_uint,
    n: c_uint,
    recsize: usize,
) -> c_uint {
    // SAFETY: the caller passes a valid `struct __kfifo`.
    let fifo = unsafe { &mut *fifo };

    if fifo.in_ == fifo.out {
        return 0;
    }

    if !tail.is_null() {
        // SAFETY: the caller guarantees `tail` is writable.
        unsafe { *tail = fifo.out.wrapping_add(recsize as u32) };
    }

    core::cmp::min(n, peek_n(fifo, recsize))
}


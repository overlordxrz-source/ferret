//! Ferret: the generic kernel FIFO, implemented in Rust.
//!
//! Replaces `lib/kfifo.c`. The C ABI in `include/linux/kfifo.h` is
//! unchanged: the same 23 exported symbols with the same signatures, the same
//! `EXPORT_SYMBOL` visibility, and the same `struct __kfifo` layout, which C
//! callers keep embedding in their own objects.
//!
//! # Model
//!
//! The FIFO is a byte ring whose size is a power of two. The indices `in` and
//! `out` are element indices that wrap at the buffer size, `mask` is
//! `size - 1` and `esize` is the element size in bytes. An empty FIFO has
//! `in == out`; a full one has `in - out == size`. Because the size is a power
//! of two, the wrap is a mask instead of a modulo.
//!
//! # Locking
//!
//! Like the C original, this implementation takes no locks. The locking
//! contract is the one documented in `include/linux/kfifo.h`: with a single
//! reader and a single writer no lock is required, otherwise the caller
//! provides one. Nothing here adds or removes synchronisation.
//!
//! # Memory ordering
//!
//! The C code issues `smp_wmb()` after copying data and before the caller
//! publishes the new index, so that a concurrent reader can never observe the
//! index advance before the data is visible. The same ordering is kept here
//! with a release fence at the same points.
//!
//! # Deviations from the C original
//!
//! Two, both in cases where the C code has undefined behaviour:
//!
//! * `__kfifo_init()` with `esize == 0` divides by zero in C (a kernel
//!   oops). Here it returns `-EINVAL` instead of trapping.
//! * `__kfifo_max_r()` with `recsize >= 4` shifts a 32-bit integer by 32 or
//!   more in C (undefined). Here the maximum is `u32::MAX`, which is the value
//!   the C code intends.
//!
//! Everything else is the same algorithm, including the quirks (for example
//! `__kfifo_peek_n()` reads two length bytes when `recsize` is zero, because
//! the C code decrements an unsigned `size_t` before testing it).

use core::ffi::{c_int, c_uint, c_void};
use core::sync::atomic::{fence, Ordering};

use kernel::bindings;
use kernel::error::code::{EFAULT, EINVAL, ENOMEM};
use kernel::prelude::*;

/// `DMA_MAPPING_ERROR` (`include/linux/dma-mapping.h`).
///
/// The C constant is `~(dma_addr_t)0`, i.e. all bits set. It is defined here
/// because bindgen cannot const-evaluate the C macro, and a `static` binding
/// would carry the *address* of the C constant rather than its value.
const DMA_MAPPING_ERROR: bindings::dma_addr_t = !0;

/// The kernel's FIFO state object: `struct __kfifo` from
/// `include/linux/kfifo.h`.
///
/// The type is generated by bindgen from the real header, so the Rust view and
/// the C view are the same object: C callers keep embedding `struct __kfifo`
/// in their own structures, and this code operates on it in place.
type Kfifo = bindings::__kfifo;

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

/// The number of elements currently stored in the FIFO.
fn stored(fifo: &Kfifo) -> u32 {
    fifo.in_.wrapping_sub(fifo.out)
}

/// The number of elements that can still be written to the FIFO.
fn unused(fifo: &Kfifo) -> u32 {
    fifo.mask
        .wrapping_add(1)
        .wrapping_sub(fifo.in_.wrapping_sub(fifo.out))
}

/// The size of the FIFO's backing buffer, in bytes.
fn buffer_len(fifo: &Kfifo) -> usize {
    (fifo.mask as usize + 1) * (fifo.esize as usize)
}

/// The FIFO's backing buffer as a byte slice.
///
/// Returns an empty slice when the FIFO has no buffer (uninitialised or
/// already freed), which keeps the helpers below free of null dereferences.
fn buffer(fifo: &Kfifo) -> &[u8] {
    let len = buffer_len(fifo);
    let data = fifo.data.cast::<u8>();

    if data.is_null() || len == 0 {
        return &[];
    }

    // SAFETY: `data` is the buffer allocated by `__kfifo_alloc()` (or
    // provided by the caller through `__kfifo_init()`), and `len` is its size
    // in bytes: `(mask + 1)` elements of `esize` bytes each. The C code
    // makes the same assumption when it memcpys into `fifo->data`.
    unsafe { core::slice::from_raw_parts(data, len) }
}

/// The FIFO's backing buffer as a mutable byte slice.
///
/// See [`buffer()`] for the safety argument.
fn buffer_mut(fifo: &mut Kfifo) -> &mut [u8] {
    let len = buffer_len(fifo);
    let data = fifo.data.cast::<u8>();

    if data.is_null() || len == 0 {
        return &mut [];
    }

    // SAFETY: as in `buffer()`, and the caller holds exclusive access to the
    // FIFO.
    unsafe { core::slice::from_raw_parts_mut(data, len) }
}

/// Copy `src` into `buf` at byte offset `off`, wrapping at the end of `buf`.
///
/// This is the Rust equivalent of the C code's pair of `memcpy()` calls: the
/// first copy stops at the end of the buffer and the second one continues at
/// the beginning of the buffer.
fn copy_bytes_in(buf: &mut [u8], off: usize, src: &[u8]) {
    let off = off.min(buf.len());
    let l = core::cmp::min(src.len(), buf.len() - off);

    buf[off..off + l].copy_from_slice(&src[..l]);

    let rest = core::cmp::min(src.len() - l, buf.len());
    buf[..rest].copy_from_slice(&src[l..l + rest]);
}

/// Copy out of `buf` at byte offset `off` into `dst`, wrapping at the end of
/// `buf`.
///
/// This is the Rust equivalent of the C code's pair of `memcpy()` calls.
fn copy_bytes_out(buf: &[u8], off: usize, dst: &mut [u8]) {
    let off = off.min(buf.len());
    let l = core::cmp::min(dst.len(), buf.len() - off);

    dst[..l].copy_from_slice(&buf[off..off + l]);

    let rest = core::cmp::min(dst.len() - l, buf.len());
    dst[l..l + rest].copy_from_slice(&buf[..rest]);
}

/// Copy `len` elements into the FIFO, starting at element index `off`.
///
/// `off` is masked to the buffer size, exactly as the C code does. `src` must
/// contain at least `len` elements; a shorter slice is truncated, which cannot
/// happen for a caller that honours the C contract.
fn copy_in(fifo: &mut Kfifo, src: &[u8], len: u32, off: u32) {
    let esize = fifo.esize as usize;
    let off = ((off & fifo.mask) as usize) * esize;
    let len = len as usize * esize;
    let n = core::cmp::min(len, src.len());

    let buf = buffer_mut(fifo);
    copy_bytes_in(buf, off, &src[..n]);

    // The C original issues `smp_wmb()` here: the data has to be visible
    // before the caller publishes the new `in` index.
    fence(Ordering::Release);
}

/// Copy `len` elements out of the FIFO, starting at element index `off`.
///
/// `off` is masked to the buffer size, exactly as the C code does.
fn copy_out(fifo: &mut Kfifo, dst: &mut [u8], len: u32, off: u32) {
    let esize = fifo.esize as usize;
    let off = ((off & fifo.mask) as usize) * esize;
    let len = len as usize * esize;
    let n = core::cmp::min(len, dst.len());

    let buf = buffer(fifo);
    copy_bytes_out(buf, off, &mut dst[..n]);

    // The C original issues `smp_wmb()` here: the data has to be visible
    // before the caller publishes the new `out` index.
    fence(Ordering::Release);
}

/// Read the length field of the record at the head of the FIFO.
///
/// Mirrors `__kfifo_peek_n()`: the first length byte is always read, the
/// second one only when `recsize != 1`. The C code decrements an unsigned
/// `size_t` before testing it, so a `recsize` of zero also reads the second
/// byte; that quirk is preserved.
fn peek_n(fifo: &Kfifo, recsize: usize) -> u32 {
    let mask = fifo.mask;
    let data = buffer(fifo);

    if data.is_empty() {
        return 0;
    }

    let mut len = data[(fifo.out & mask) as usize] as u32;

    if recsize.wrapping_sub(1) != 0 {
        len |= (data[((fifo.out.wrapping_add(1)) & mask) as usize] as u32) << 8;
    }

    len
}

/// Write the length field of the record at the tail of the FIFO.
///
/// Mirrors `__kfifo_poke_n()`.
fn poke_n(fifo: &mut Kfifo, n: u32, recsize: usize) {
    let mask = fifo.mask;
    let in_ = fifo.in_;

    let buf = buffer_mut(fifo);
    if buf.is_empty() {
        return;
    }

    buf[(in_ & mask) as usize] = n as u8;

    if recsize > 1 {
        buf[((in_.wrapping_add(1)) & mask) as usize] = (n >> 8) as u8;
    }
}

/// `roundup_pow_of_two()` for a run-time value (`include/linux/log2.h`).
///
/// The C helper is `1UL << fls_long(n - 1)`. For `n == 0` the C code shifts
/// by the word width, which is undefined; this implementation returns 1,
/// which takes the same "size < 2" error path as the C code takes for every
/// other small size.
fn roundup_pow_of_two(n: u32) -> u32 {
    if n <= 1 {
        return 1;
    }

    1u32 << (u32::BITS - (n - 1).leading_zeros())
}

/// `rounddown_pow_of_two()` for a run-time value (`include/linux/log2.h`).
///
/// The C helper is `1UL << (fls_long(n) - 1)`, which is undefined for
/// `n == 0`; this implementation returns 0 there.
fn rounddown_pow_of_two(n: u32) -> u32 {
    if n == 0 {
        return 0;
    }

    1u32 << (u32::BITS - n.leading_zeros()) >> 1
}

/// `is_power_of_2()` (`include/linux/log2.h`).
fn is_power_of_2(n: u32) -> bool {
    n != 0 && n & (n - 1) == 0
}

/// Divide `n` by `d`, rounding up (`DIV_ROUND_UP()`).
fn div_round_up(n: usize, d: usize) -> usize {
    // A zero divisor is a kernel oops in C (`DIV_ROUND_UP()` divides); the
    // FIFO's element size is never zero in practice, and clamping keeps this
    // path free of a panic.
    n.div_ceil(d.max(1))
}

